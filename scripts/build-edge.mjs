// Bundles the server engine (src/server/edgeEntry.ts) into supabase/functions/edt-engine/engine.js
// for the Deno Edge Function. The bundle contains the hidden case content; it is deployed only to
// the server and is never served to participants.
import { build } from 'esbuild';
import { readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { execSync } from 'node:child_process';

const root = new URL('..', import.meta.url).pathname;
const outfile = join(root, 'supabase/functions/edt-engine/engine.js');
let commit = 'uncommitted';
try {
  commit = execSync('git rev-parse --short HEAD', { cwd: root }).toString().trim();
} catch {
  /* not a git checkout */
}
await build({
  entryPoints: [join(root, 'src/server/edgeEntry.ts')],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: ['es2022'],
  minify: true,
  legalComments: 'none',
  banner: { js: `// GENERATED by scripts/build-edge.mjs from source commit ${commit}. Do not edit.` },
  outfile,
  logLevel: 'warning',
});
const js = readFileSync(outfile, 'utf8');
for (const forbidden of ['localStorage', 'document.', 'window.']) {
  if (js.includes(forbidden)) console.warn(`note: engine bundle references ${forbidden}`);
}
console.log(`built supabase/functions/edt-engine/engine.js (${Math.round(statSync(outfile).size / 1024)} KB)`);
